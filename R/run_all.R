#!/usr/bin/env Rscript
#
# run_all.R  -  master script: reproduce all analyses end-to-end.
# Usage:  Rscript R/run_all.R   (from the project root, or anywhere)
#
# Willem M. (Wim) Otte, w.m.otte@umcutrecht.nl
# ==============================================================================
t0 <- Sys.time()
args <- commandArgs(FALSE)
fa <- grep("^--file=", args, value = TRUE)
script_dir <- if (length(fa)) dirname(normalizePath(sub("^--file=", "", fa[1]))) else file.path(getwd(), "R")
source(file.path(script_dir, "00_config.R"))
source(file.path(CFG$root, "R", "plot_theme.R"))
source(file.path(CFG$root, "R", "lib_ml.R"))
steps <- c("01_prepare_data.R", "02_descriptives.R", "03_univariable.R", "04_legacy_bridge.R",
           "05_ml_main.R", "06_ml_sensitivity.R", "07_shap_stability.R", "08_figures.R",
           "09_report.R")
for (s in steps) {
  message("\n=========== ", s, " ===========")
  source(file.path(CFG$root, "R", s))
}

# ---- Software provenance -----------------------------------------------------
prov <- file.path(CFG$dir_tab, "session_provenance.txt")
si <- utils::sessionInfo()
pkgs <- c(si$otherPkgs, si$loadedOnly)
writeLines(c(
  "# Software provenance for the neonatal cEEG revision analyses",
  "# Regenerated by R/run_all.R on every run.",
  sprintf("r_version\t%s", si$R.version$version.string),
  sprintf("platform\t%s", si$platform),
  sprintf("running\t%s", si$running %||% NA_character_),
  sprintf("rng_kind\t%s", paste(RNGkind(), collapse = " / ")),
  sprintf("seed\t%d", CFG$seed),
  sprintf("cv\t%d-fold x %d repeats (inner %d-fold)", CFG$cv_folds, CFG$cv_repeats, CFG$inner_folds),
  sprintf("permutations\t%d", CFG$n_perm),
  "",
  "# package\tversion",
  sort(vapply(pkgs, function(p) sprintf("%s\t%s", p$Package, p$Version), ""))
), prov)
message("[run_all] wrote software provenance to ", prov)
message(sprintf("\n[run_all] DONE in %.1f min. Tables and figures in output/.",
                as.numeric(difftime(Sys.time(), t0, units = "mins"))))
